// Loads the AI resume analysis (NVIDIA Nemotron, called by the Flask backend) after the page renders.
// All AI text is inserted with textContent, never innerHTML, so resume or model text cannot inject HTML.
document.addEventListener('DOMContentLoaded', () => {
  const card = document.getElementById('ai-resume-card');
  if (!card || card.dataset.enabled !== 'true') return;
  const statusBox = document.getElementById('ai-resume-status');
  const body = document.getElementById('ai-resume-body');
  const retry = document.getElementById('ai-resume-retry');
  let running = false;

  function el(tag, className, text) {
    const node = document.createElement(tag);
    if (className) node.className = className;
    if (text !== undefined) node.textContent = text;
    return node;
  }
  function section(title) {
    const wrap = el('div', 'ai-block');
    wrap.appendChild(el('h4', null, title));
    body.appendChild(wrap);
    return wrap;
  }
  function addList(title, items) {
    if (!items || !items.length) return;
    const wrap = section(title);
    const ul = el('ul', 'ai-list');
    items.forEach((t) => ul.appendChild(el('li', null, t)));
    wrap.appendChild(ul);
  }
  function addChips(title, items, extraClass) {
    if (!items || !items.length) return;
    const wrap = section(title);
    const chips = el('div', 'ai-chips');
    items.forEach((t) => chips.appendChild(el('span', 'ai-chip' + (extraClass ? ' ' + extraClass : ''), t)));
    wrap.appendChild(chips);
  }

  function render(a, targetRole) {
    body.textContent = '';
    section('Summary').appendChild(el('p', 'ai-text', a.summary));
    if (a.role_match_score !== null && a.role_match_score !== undefined) {
      const wrap = section('Approximate match with ' + (targetRole || 'the selected role'));
      const row = el('div', 'score-row');
      row.appendChild(el('span', null, 'AI-estimated match'));
      const bar = el('div', 'bar');
      const fill = el('span');
      fill.style.width = Math.max(0, Math.min(100, a.role_match_score)) + '%';
      bar.appendChild(fill);
      row.append(bar, el('strong', null, a.role_match_score + '%'));
      wrap.appendChild(row);
      if (a.role_match_note) wrap.appendChild(el('p', 'ai-text', a.role_match_note));
      wrap.appendChild(el('p', 'ai-note', a.role_match_disclaimer));
    }
    addChips('Skills found in the resume', a.detected_skills);
    addList('Education', a.education);
    if (a.experience_summary) section('Experience & internships').appendChild(el('p', 'ai-text', a.experience_summary));
    addList('Projects and your stated contribution', a.project_summary);
    addList('Certifications & achievements', a.certifications_achievements);
    addList('Strengths', a.strengths);
    if (a.skill_gaps && a.skill_gaps.length) {
      const wrap = section('Skills to show or build for this role');
      const ul = el('ul', 'ai-list');
      a.skill_gaps.forEach((g) => {
        const label = g.status === 'weakly_shown' ? 'only weakly shown in the resume' : 'not mentioned in the resume';
        ul.appendChild(el('li', null, g.skill + ' — ' + label + (g.note ? '. ' + g.note : '')));
      });
      wrap.appendChild(ul);
      wrap.appendChild(el('p', 'ai-note', '“Not mentioned” means the resume does not show it; it does not prove you lack the skill.'));
    }
    addChips('Roles that fit your documented skills', a.recommended_roles);
    addList('How to improve the resume', a.resume_improvements);
    body.appendChild(el('p', 'ai-note', 'Generated by NVIDIA Nemotron from your resume text (contact details removed before sending). AI output can be wrong — check it yourself.'));
  }

  async function run(force) {
    if (running) return;
    running = true;
    retry.style.display = 'none';
    retry.disabled = true;
    statusBox.className = 'ai-status';
    statusBox.textContent = 'Analysing your resume with NVIDIA Nemotron… this can take a few seconds.';
    body.textContent = '';
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 120000);
    try {
      const response = await fetch('/api/resume/analyze', {
        method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ force: !!force }), signal: controller.signal,
      });
      const data = await response.json().catch(() => ({}));
      if (!response.ok || !data.ok) throw new Error(data.error || 'The AI analysis is unavailable right now.');
      statusBox.textContent = '';
      render(data.analysis, data.target_role);
    } catch (err) {
      statusBox.className = 'ai-status ai-error';
      statusBox.textContent = (err.name === 'AbortError' ? 'The AI analysis took too long.' : (err.message || 'The AI analysis failed.'))
        + ' The keyword analysis above is still available.';
      retry.style.display = '';
    } finally {
      clearTimeout(timer);
      retry.disabled = false;
      running = false;
    }
  }

  retry.addEventListener('click', () => run(true));
  run(false);
});
